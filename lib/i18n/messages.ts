export const CATALOGS: Record<Locale, Messages> = { en, hi, kn, bn, mr, te };

/**
 * Shared translator usable on the server (RSC) and client. Falls back to the
 * English string, then the raw key. Optional `vars` interpolates `{name}`
 * placeholders (used for pluralized counts like "{n} cases").
 */
export function translate(
  locale: Locale,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  let str: string = CATALOGS[locale]?.[key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      // Literal placeholder matching + literal replacement: split/join treats
      // both the key token (`{k}`) and the value as plain strings, so arbitrary
      // keys and `$`-bearing values can never be interpreted as regex syntax or
      // replacement specials. Unsupplied placeholders are left intact.
      str = str.split(`{${k}}`).join(String(v));
    }
  }
  return str;
}
